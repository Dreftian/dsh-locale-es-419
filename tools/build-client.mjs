import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { join, dirname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const localeRoot = join(root, 'locale');

const LANGS = [
  { id: 'es-419', label: 'Español (Latinoamérica)' },
  { id: 'es', label: 'Español' },
];

function loadLang(langId) {
  const dir = join(localeRoot, langId);
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => f.endsWith('.json'))
    .map((f) => [basename(f, '.json'), JSON.parse(readFileSync(join(dir, f), 'utf8'))])
    .sort(([a], [b]) => (a < b ? -1 : 1));
}

const es419Entries = loadLang('es-419');
if (!es419Entries.length) throw new Error('No es-419 dictionaries found');

const perLang = new Map();
perLang.set('es-419', es419Entries);
perLang.set('es', es419Entries);

const langSrc = JSON.stringify(LANGS, null, 2);
const dictSrc = JSON.stringify(
  Object.fromEntries(LANGS.map(({ id }) => [id, Object.fromEntries(perLang.get(id))])),
  null,
  2,
);

const client = `// dsh-locale-es-419: Latin American Spanish language pack for DeepSeek Harness
// Generated by tools/build-client.mjs
window.__ModuleLoader__.load({
  id: "dsh-locale-es-419",
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
    Object.defineProperty(exports, Symbol.toStringTag, { value: "Module" });

    const LANGS = ${langSrc};
    const DICTS = ${dictSrc};

    const inject = ["locale"];

    function apply(ctx) {
      for (const { id, label } of LANGS) {
        ctx.effect(() => {
          try {
            ctx.locale.addLanguage({ id, label, fallback: "en" });
          } catch (error) {
            if (!/already registered/.test(String(error && error.message))) throw error;
          }
          return () => {};
        }, "locale-es-419: language " + id);
      }
      for (const [lang, namespaces] of Object.entries(DICTS)) {
        for (const [ns, dict] of Object.entries(namespaces)) {
          ctx.effect(() => {
            try {
              return ctx.locale.register(ns, { [lang]: dict });
            } catch (error) {
              if (!/already has locale/.test(String(error && error.message))) throw error;
              return () => {};
            }
          }, "locale-es-419: " + lang + "/" + ns);
        }
      }
    }

    exports.apply = apply;
    exports.inject = inject;
    return module.exports;
  }
});
`;

writeFileSync(join(root, 'lib', 'client.js'), client, 'utf8');
console.log(`Successfully generated lib/client.js with ${es419Entries.length} namespaces for es-419`);
